#!/usr/bin/env node
/**
 * gen_tool_docs.js — write docs/tools.md from the tool schemas.
 *
 *   node scripts/gen_tool_docs.js            rewrite docs/tools.md
 *   node scripts/gen_tool_docs.js --check    exit 1 if docs/tools.md is stale
 *
 * Every tool module under bots/agent/tools/ exports a factory that returns
 * tool definitions (name, description, input_schema, defaultInterrupts,
 * uninterruptible, parallelSafe). This script builds them with stub
 * dependencies (no bot, no server) and renders the schemas, plus the
 * failure reasons each module declares with fail('…') / partial('…').
 * Hand-written text lives in this file (PREAMBLE, MEMORY_TOOL) so the whole
 * document regenerates from one command: npm run docs.
 */
