const PREAMBLE = `# Tools reference

*Generated by \`scripts/gen_tool_docs.js\` from the schemas in \`bots/agent/tools/\`;
run \`npm run docs\` after changing a tool. \`npm test\` fails when this file is stale.*

The agent plays Minecraft only through these tools. Each turn the model
receives the list below as the API's tool definitions, calls one or more,
and gets every result back as JSON. How the loop sequences calls, events
and interrupts is described in [agent-loop.md](agent-loop.md); how a tool
is implemented on top of the world substrate is in
[world-substrate.md](world-substrate.md).

## Result shape

Every tool answers with one JSON object (\`bots/agent/tools/result.js\`):

| Field | Meaning |
|---|---|
| \`status\` | \`ok\`, \`partial\` (something useful happened, then it stopped), \`failed\`, \`interrupted\` (an event pulled the bot out), \`unsupported\` |
| \`reason\` | a stable machine token for anything but plain \`ok\` (for example \`no_path\`, \`block_not_found\`, \`need_bucket\`); the per-group lists below are the tokens each module declares |
| \`by\`, \`detail\` | only with \`interrupted\`: the event that fired and what it carried (a damage event carries hp, amount, cause, attacker) |
| \`hint\` | free text telling the model what to try next, when the tool knows |
| \`elapsed_s\` | wall time |
| other fields | tool-specific: positions, counts, what was gained, what remains |

Tools never throw to the loop: an exception becomes \`failed\` with
\`reason: "exception:<message>"\` so the transcript stays truthful and the
model always gets its turn back.

## Interrupts

Actuators (anything that takes time) accept \`interrupt_on\`, a list of
events that end the call early: ${INTERRUPT_SCHEMA.items.enum.map((e) => `\`${e}\``).join(', ')}.
Each tool has a default (shown as *interrupts* below); pass \`[]\` to stay
heads-down. Lava, drowning and death always interrupt, and a few tools are
*uninterruptible* (only death or shutdown cancel them) so an escape finishes
before the model gets to reconsider. Interrupted calls report what was
achieved before the event, and the event itself is delivered to the model
with the result. Events that do not interrupt (\`dusk\`, \`dawn\`, \`job_done\`,
faction messages) arrive as \`[events]\` lines with the next turn.

Tools marked *parallel-safe* may be called in the same turn as other tools;
everything else runs one at a time in the order the model asked.
`;

